using System.Text.Json;
using Apache.Arrow;
using Apache.Arrow.Ipc;
using Apache.Arrow.Types;
using QueryFarm.Vgi.Internal;
using QueryFarm.Vgi.Protocol;
using QueryFarm.VgiRpc.Reflection;
using Xunit;

namespace QueryFarm.Vgi.Tests;
public sealed class MetadataCollectionTests
{
    public static List<FunctionInfo> BinaryFunctions() => Enumerable.Range(0, 7).Select(i => new FunctionInfo {
        Name = $"f{i}", SchemaPath = [i % 2 == 0 ? "main" : "extra"], FunctionType = FunctionType.Scalar,
        Arguments = [0xff, 0, (byte)(i < 3 ? 0x80 : 0x81)], OutputSchema = [],
        ParameterDefaultValues = (i % 3) switch { 0 => null, 1 => [], _ => [0xff, 0] },
    }).ToList();

    [Fact]
    public void BinaryDictionariesDeduplicateContentAndPreserveNullEmptyAndNonUtf8()
    {
        var rows = BinaryFunctions();
        var singleton = EmbeddedIpc.Decode<FunctionInfo>(EmbeddedIpc.Encode(rows[0]));
        Assert.Equal(rows[0].Arguments, singleton.Arguments);
        Assert.Null(singleton.ParameterDefaultValues);
        var bytes = MetadataCollections.Encode(rows, 3)!;
        using var input = new MemoryStream(bytes);
        using var reader = new ArrowStreamReader(input);
        using var first = reader.ReadNextRecordBatch()!;
        var arguments = Assert.IsType<DictionaryArray>(first.Column(5));
        Assert.IsType<Int32Array>(arguments.Indices);
        Assert.Equal(2, arguments.Dictionary.Length);
        Assert.Equal(JsonSerializer.Serialize(rows), JsonSerializer.Serialize(MetadataCollections.Decode<FunctionInfo>(bytes)));
    }

    [Fact]
    public void NullDictionaryValuesAreNullableDefaultsAndInvalidRequiredArguments()
    {
        var schema = SchemaDerivation.InnerSchemaFor(typeof(FunctionInfo));
        var properties = schema.FieldsList.Select(f => typeof(FunctionInfo).GetProperty(ValueCodec.FindClrPropertyName(typeof(FunctionInfo), f))!).ToArray();
        foreach (var fieldName in new[] { "parameter_default_values", "arguments" })
        {
            using var row = ValueCodec.BuildRow(schema, properties.Select(p => p.GetValue(BinaryFunctions()[1])).ToArray());
            var columns = row.Arrays.ToArray();
            var index = schema.GetFieldIndex(fieldName);
            columns[index] = new DictionaryArray((DictionaryType)schema.GetFieldByIndex(index).DataType, new Int32Array.Builder().Append(0).Build(), new BinaryArray.Builder().AppendNull().Build());
            using var output = new MemoryStream();
            using (var writer = new ArrowStreamWriter(output, schema, leaveOpen: true)) { writer.WriteRecordBatch(new RecordBatch(schema, columns, 1)); writer.WriteEnd(); }
            if (fieldName == "arguments") Assert.Throws<InvalidOperationException>(() => MetadataCollections.Decode<FunctionInfo>(output.ToArray()));
            else Assert.Null(MetadataCollections.Decode<FunctionInfo>(output.ToArray())[0].ParameterDefaultValues);
        }
    }

    [Fact]
    public void BinaryDictionaryReplacementAcrossRecordBatchesIsDecoded()
    {
        // Generated by Vectors/generate_function_binary_dictionary_replacement.py.
        // Apache.Arrow's writer emits only initial dictionaries, while foreign workers
        // may legally replace dictionaries between batches.
        var bytes = File.ReadAllBytes(Path.Combine(AppContext.BaseDirectory, "Vectors", "function_binary_dictionary_replacement.arrow"));
        var rows = MetadataCollections.Decode<FunctionInfo>(bytes);
        Assert.Equal(3, rows.Count);
        Assert.Equal(new byte[] { }, rows[0].Arguments); Assert.Equal(new byte[] { 0, 255 }, rows[0].OutputSchema); Assert.Null(rows[0].ParameterDefaultValues);
        Assert.Equal(new byte[] { 0, 255 }, rows[1].Arguments); Assert.Empty(rows[1].OutputSchema); Assert.Empty(rows[1].ParameterDefaultValues!);
        Assert.Equal(new byte[] { 128, 0, 254 }, rows[2].Arguments); Assert.Equal(new byte[] { 255, 0, 129 }, rows[2].OutputSchema); Assert.Equal(new byte[] { 0, 255, 128 }, rows[2].ParameterDefaultValues);
    }

    [Fact]
    public void DictionariesRoundTripEveryRowAndBatchAcrossSchemas()
    {
        var rows = Enumerable.Range(0, 7).Select(i => new IndexInfo { Name = $"i{i}", SchemaPath = [i % 2 == 0 ? "main" : "other"], TableName = "table", IndexType = "ART", ConstraintType = i % 2 == 0 ? IndexConstraintType.Primary : IndexConstraintType.Unique, Tags = new() { ["tag"] = "value" }, Expressions = ["column"] }).ToList();
        var encoded = MetadataCollections.Encode(rows, 2)!;
        Assert.Equal(JsonSerializer.Serialize(rows), JsonSerializer.Serialize(MetadataCollections.Decode<IndexInfo>(encoded)));
        Assert.Null(MetadataCollections.Encode<IndexInfo>([]));
        Assert.Throws<InvalidOperationException>(() => MetadataCollections.Decode<IndexInfo>([.. encoded, 1]));
    }
    [Fact]
    public void RequiredFieldsAndPathComponentsAreValidated()
    {
        var expected = SchemaDerivation.InnerSchemaFor(typeof(SchemaInfo));
        var fields = expected.FieldsList.Select(f => f.Name == "path" ? new Field(f.Name, f.DataType, true) : f).ToArray();
        var nullable = new Schema(fields, null);
        using var row = ValueCodec.BuildRow(nullable, [null, new Dictionary<string,string>(), null, null]);
        using var output = new MemoryStream();
        using (var writer = new ArrowStreamWriter(output, nullable, leaveOpen: true)) { writer.WriteStart(); writer.WriteRecordBatch(row); writer.WriteEnd(); }
        Assert.Throws<InvalidOperationException>(() => MetadataCollections.Decode<SchemaInfo>(output.ToArray()));
        var badPath = MetadataCollections.Encode(new[] { new SchemaInfo { Path = [""] } });
        Assert.Throws<InvalidOperationException>(() => MetadataCollections.DecodeCatalog(new CatalogContentsResponse { Schemas = badPath }));
    }
}
